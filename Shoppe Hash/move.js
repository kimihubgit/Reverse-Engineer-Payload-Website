// convert.js - Chuyển escaped string sang binary và dump unicode escape

function unescapeToBytes(escaped) {
    // Unescape \xHH, \r, v.v.
    const unescaped = escaped.replace(/\\x([0-9a-fA-F]{2})/g, (match, hex) => String.fromCharCode(parseInt(hex, 16)));
    const bytes = new Uint8Array(unescaped.length);
    for (let i = 0; i < unescaped.length; i++) {
        bytes[i] = unescaped.charCodeAt(i) & 0xff;
    }
    return bytes;
}

function bytesToUnicodeEscape(bytes) {
    let result = '';
    for (let byte of bytes) {
        if (byte < 32 || byte > 126) { // Non-printable -> \uXXXX
            result += '\\u' + byte.toString(16).padStart(4, '0');
        } else {
            result += String.fromCharCode(byte);
        }
    }
    return result;
}



function g(n, t) {
    for (r = t.length, o = "", a = 0; a < n.length; a++)
        o += String.fromCharCode(n.charCodeAt(a) ^ t.charCodeAt(a % r));
    return o
}


